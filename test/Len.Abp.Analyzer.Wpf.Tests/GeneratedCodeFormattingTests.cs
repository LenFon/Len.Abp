namespace Len.Abp.Analyzer.Wpf.Tests;

/// <summary>
/// 锁定生成代码的排版。
/// </summary>
/// <remarks>
/// 生成器曾把类型体直接拼在 <c>{</c> 之后且不加缩进，导致成员顶格、闭合括号与前一行粘成 <c>}}</c>；
/// 也曾用 <c>Join</c> 拼接特性与声明，在两者之间留下空行，使特性与它修饰的成员分离。
/// 这里把排版拆成独立规则，对每个生成器的每种输出形态分别校验，
/// 失败时能直接看出是哪条规则、哪个场景。
/// </remarks>
public class GeneratedCodeFormattingTests
{
    /// <summary>
    /// 全部待测场景名。理论数据只传字符串，保证可被 Test Explorer 逐行枚举。
    /// </summary>
    public static TheoryData<string> Cases { get; } = BuildCases();

    private static readonly ConcurrentDictionary<string, FormattingCase> Registry = BuildRegistry();

    private static readonly ConcurrentDictionary<string, IReadOnlyList<GeneratedSource>> SourceCache = new();

    #region 文件级规则

    /// <summary>
    /// 第一行必须是自动生成标记，便于 IDE 与代码评审识别。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void FirstLine_IsAutoGeneratedHeader(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            Assert.Equal("// <auto-generated />", GetLines(source)[0]);
        }
    }

    /// <summary>
    /// 文件头、可空指令、命名空间之间各留一个空行。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void Preamble_SectionsSeparatedBySingleBlankLine(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            Assert.Equal("", lines[1]);
            Assert.Equal("#nullable enable", lines[2]);
            Assert.Equal("", lines[3]);

            var namespaceIndex = Array.FindIndex(lines, line => line.StartsWith("namespace ", StringComparison.Ordinal));

            Assert.True(namespaceIndex > 0, "缺少命名空间声明");
            Assert.Equal("", lines[namespaceIndex - 1]);
            Assert.Equal("", lines[namespaceIndex + 1]);
        }
    }

    /// <summary>
    /// 统一使用 LF，且文件以单个换行结尾。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void LineEndings_AreLfWithSingleTrailingNewline(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            Assert.DoesNotContain('\r', source.Text);
            Assert.EndsWith("\n", source.Text);
            Assert.False(source.Text.EndsWith("\n\n", StringComparison.Ordinal), "文件末尾有多余空行");
        }
    }

    #endregion 文件级规则

    #region 缩进规则

    /// <summary>
    /// 成员声明的首列等于其所在类型的嵌套深度乘以 4。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void MemberDeclaration_IndentedByNestingDepth(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            foreach (var member in Parse(source).DescendantNodes().OfType<MemberDeclarationSyntax>())
            {
                if (member is BaseNamespaceDeclarationSyntax)
                {
                    continue;
                }

                var depth = member.Ancestors().OfType<TypeDeclarationSyntax>().Count();
                var line = lines[GetLine(member)];

                Assert.Equal(depth * 4, CountIndent(line));
            }
        }
    }

    /// <summary>
    /// 类型声明的闭合括号独占一行，并与声明同层。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void TypeClosingBrace_OnOwnLineAndAligned(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            foreach (var type in Parse(source).DescendantNodes().OfType<TypeDeclarationSyntax>())
            {
                var depth = type.Ancestors().OfType<TypeDeclarationSyntax>().Count();
                var line = lines[GetLine(type.CloseBraceToken)];

                Assert.Equal("}", line.Trim());
                Assert.Equal(depth * 4, CountIndent(line));
            }
        }
    }

    /// <summary>
    /// 闭合括号不能与前一行粘连成 <c>}}</c>。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void ClosingBrace_NotGluedToPreviousLine(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            Assert.DoesNotContain("}}", source.Text);
        }
    }

    /// <summary>
    /// 嵌套类型逐层展开，每层增加 4 个空格。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void NestedType_IndentedPerLevel(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            foreach (var type in Parse(source).DescendantNodes().OfType<TypeDeclarationSyntax>())
            {
                var depth = type.Ancestors().OfType<TypeDeclarationSyntax>().Count();
                var line = lines[GetLine(type)];

                Assert.Equal(depth * 4, CountIndent(line));
            }
        }
    }

    #endregion 缩进规则

    #region 空行规则

    /// <summary>
    /// 不允许出现连续空行。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void NoConsecutiveBlankLines(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            for (var i = 1; i < lines.Length; i++)
            {
                Assert.False(
                    lines[i].Length == 0 && lines[i - 1].Length == 0,
                    $"第 {i + 1} 行出现连续空行"
                );
            }
        }
    }

    /// <summary>
    /// 相邻成员之间恰好一个空行，首个成员紧跟类型开括号。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void Members_SeparatedBySingleBlankLine(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            foreach (var type in Parse(source).DescendantNodes().OfType<TypeDeclarationSyntax>())
            {
                for (var i = 1; i < type.Members.Count; i++)
                {
                    var startLine = GetMemberStartLine(type.Members[i], lines);

                    Assert.Equal("", lines[startLine - 1]);
                    Assert.NotEqual("", lines[startLine - 2]);
                }
            }
        }
    }

    /// <summary>
    /// 特性与 XML 文档必须紧贴其声明，中间不能有空行。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void AttributesAndDocs_AdjacentToDeclaration(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            for (var i = 0; i + 1 < lines.Length; i++)
            {
                if (lines[i + 1].Length != 0)
                {
                    continue;
                }

                var trimmed = lines[i].TrimStart();

                Assert.False(
                    trimmed.StartsWith('[') || trimmed.StartsWith("///", StringComparison.Ordinal),
                    $"第 {i + 1} 行的特性或注释后出现空行"
                );
            }
        }
    }

    /// <summary>
    /// 不输出空的 XML 注释行（<c>///</c> 后无内容）。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void NoEmptyXmlCommentLines(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            for (var i = 0; i < lines.Length; i++)
            {
                Assert.False(lines[i].Trim() == "///", $"第 {i + 1} 行是空注释");
            }
        }
    }

    #endregion 空行规则

    #region 空白字符规则

    /// <summary>
    /// 行尾不允许残留空白。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void NoTrailingWhitespace(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var lines = GetLines(source);

            for (var i = 0; i < lines.Length; i++)
            {
                Assert.Equal(lines[i].TrimEnd(), lines[i]);
            }
        }
    }

    /// <summary>
    /// 缩进只用空格，不使用制表符。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void NoTabCharacters(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            Assert.DoesNotContain('\t', source.Text);
        }
    }

    #endregion 空白字符规则

    #region 结构规则

    /// <summary>
    /// 生成结果必须是语法合法的 C#，排版规则才有意义。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void GeneratedCode_ParsesWithoutSyntaxErrors(string caseName)
    {
        foreach (var source in GetSources(caseName))
        {
            var errors = Parse(source)
                .GetDiagnostics()
                .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
                .Where(diagnostic => diagnostic.Id != "CS1029") // #error 指令本身是预期的诊断
                .ToArray();

            Assert.Empty(errors);
        }
    }

    /// <summary>
    /// 每个场景都至少产出一个源文件，避免用例因生成器静默跳过而空转。
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void Generator_ProducesAtLeastOneSource(string caseName)
    {
        Assert.NotEmpty(GetSources(caseName));
    }

    #endregion 结构规则

    #region 辅助方法

    private static IReadOnlyList<GeneratedSource> GetSources(string caseName) =>
        SourceCache.GetOrAdd(
            caseName,
            name =>
            {
                var testCase = Registry[name];

                return GeneratorTestHost.Run(testCase.CreateGenerator(), GeneratorTestSources.With(testCase.Snippet));
            }
        );

    private static SyntaxNode Parse(GeneratedSource source) => CSharpSyntaxTree.ParseText(source.Text).GetRoot();

    private static string[] GetLines(GeneratedSource source) => source.Text.Split('\n');

    private static int GetLine(SyntaxNode node) => node.GetLocation().GetLineSpan().StartLinePosition.Line;

    private static int GetLine(SyntaxToken token) => token.GetLocation().GetLineSpan().StartLinePosition.Line;

    private static int CountIndent(string line) => line.Length - line.TrimStart().Length;

    /// <summary>
    /// 取成员块的起始行：从首个记号向上跳过特性与 XML 文档行。
    /// </summary>
    private static int GetMemberStartLine(MemberDeclarationSyntax member, string[] lines)
    {
        var line = GetLine(member);

        while (line > 0)
        {
            var previous = lines[line - 1].TrimStart();

            if (!previous.StartsWith('[') && !previous.StartsWith("///", StringComparison.Ordinal))
            {
                break;
            }

            line--;
        }

        return line;
    }

    private static TheoryData<string> BuildCases()
    {
        var cases = new TheoryData<string>();

        foreach (var name in BuildRegistry().Keys)
        {
            cases.Add(name);
        }

        return cases;
    }

