/// <summary>
/// 一个待校验的生成场景。
/// </summary>
/// <param name="Name">场景名，同时用作缓存键与测试显示名。</param>
/// <param name="CreateGenerator">创建生成器的工厂，避免多个用例共享同一实例。</param>
/// <param name="Snippet">待测类型声明。</param>
internal sealed record FormattingCase(string Name, Func<IIncrementalGenerator> CreateGenerator, string Snippet)
{
    /// <inheritdoc/>
    public override string ToString() => Name;
}
