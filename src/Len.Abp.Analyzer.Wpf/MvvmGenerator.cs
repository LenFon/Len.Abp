using Len.Abp.Analyzer;
using Microsoft.CodeAnalysis;

[Generator]
internal class MvvmGenerator()
    : BasicGenerator<MvvmGenerator.MvvmData>("Mvvm", "Len.Abp.Wpf.Mvvm.ViewAttribute", "Len.Abp.Wpf.Mvvm.ViewAttribute`1")
{
    /// <inheritdoc/>
    protected override string CreateFileName((ClassData Class, MvvmData Data, string Version) context) => $"{context.Class.HintName}.g.cs";

    /// <inheritdoc/>
    protected override string CreateSourceCode((ClassData Class, MvvmData Data, string Version) context)
    {
        var selfDeclaration = GeneratedCode.Lines(
            $"partial {(context.Class.IsRecord ? "record" : "class")} {context.Class.Name} : {(context.Data.IsShell ? "global::Len.Abp.Wpf.IShell, " : string.Empty)}global::Len.Abp.Wpf.Mvvm.IView<{context.Data.ViewModel}>{GetLifetimeInterface(context)}"
        );

        var members = GeneratedCode.Join(
            GeneratedCode.Lines(
                "///<inheritdoc/>",
                "[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]",
                $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{nameof(MvvmGenerator)}\", \"{context.Version}\")]",
                $"public {context.Data.ViewModel} ViewModel => ({context.Data.ViewModel})DataContext;"
            ),
            GeneratedCode.Lines(
                "///<inheritdoc/>",
                "[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]",
                $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{nameof(MvvmGenerator)}\", \"{context.Version}\")]",
                "object global::Len.Abp.Wpf.Mvvm.IView.ViewModel => ViewModel;"
            ),
            GeneratedCode.Lines(
                "///<inheritdoc/>",
                "[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]",
                $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{nameof(MvvmGenerator)}\", \"{context.Version}\")]",
                $"public string ViewName => \"{(context.Data.ViewName ?? string.Empty).ToCSharpStringLiteral()}\";"
            ),
            GetConstructor(context)
        );

        // 键控服务与 ExposeServices 属于同一组特性，中间不能有空行。
        var attributes = GetExposeKeyedServices(context)
            + $"[global::Volo.Abp.DependencyInjection.ExposeServices({(context.Data.IsShell ? "typeof(global::Len.Abp.Wpf.IShell), " : string.Empty)}typeof({context.Class.Name}), typeof(global::Len.Abp.Wpf.Mvvm.IView<{context.Data.ViewModel}>), typeof(global::Len.Abp.Wpf.Mvvm.IView<object>))]\n";

        // 特性必须紧贴类型声明，中间不能有空行，否则特性会失去目标。
        return GeneratedCode.Join(
            "// <auto-generated />",
            "#nullable enable",
            GetConstructorErrorDirective(context),
            context.Class.NamespaceDeclaration,
            attributes + context.Class.WrapInTypeDeclarations(members, selfDeclaration)
        );
    }

    /// <summary>
    /// 生成通过构造函数注入视图模型的构造函数。
    /// </summary>
    /// <remarks>
    /// 视图由容器解析，构造函数注入让依赖显式可见，且不依赖 Autofac 的属性注入。
    /// <c>: this()</c> 链到用户声明的无参构造函数，保证 <c>InitializeComponent</c> 照常执行。
    /// 用户已手写接收视图模型的构造函数时不再生成，避免重复成员。
    /// </remarks>
    private static string GetConstructor((ClassData Class, MvvmData Data, string Version) context)
    {
        if (context.Data.HasViewModelConstructor)
        {
            return string.Empty;
        }

        return GeneratedCode.Lines(
            "/// <summary>",
            "/// 注入视图模型并写入 <c>DataContext</c>。",
            "/// </summary>",
            "[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]",
            $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{nameof(MvvmGenerator)}\", \"{context.Version}\")]",
            $"public {context.Class.SimpleName}({context.Data.ViewModel} viewModel) : this()",
            "{",
            "    DataContext = viewModel;",
            "}"
        );
    }

    /// <summary>
    /// 视图缺少无参构造函数时，在生成文件中输出 <c>#error</c>，把问题定位到具体视图。
    /// </summary>
    /// <remarks>
    /// 生成的构造函数依赖 <c>: this()</c>。若视图只声明了带参构造函数，
    /// 编译器会报 CS1729，错误信息指向生成文件且难以理解；这里提前给出可读的提示。
    /// </remarks>
    private static string GetConstructorErrorDirective((ClassData Class, MvvmData Data, string Version) context)
    {
        // 用户已手写接收视图模型的构造函数时不会生成新构造函数，也就不需要链式调用。
        if (context.Data.HasViewModelConstructor || context.Class.CanChainToParameterlessConstructor)
        {
            return string.Empty;
        }

        return $"#error 视图 {context.Class.FullName} 声明了构造函数但没有无参构造函数，生成的构造函数无法通过 : this() 链式调用。请补充一个无参构造函数。";
    }

    /// <summary>
    /// 生成视图的生命周期标记接口。
    /// </summary>
    /// <remarks>
    /// <c>IShell</c> 本身继承 <c>ISingletonDependency</c>，Shell 视图不能再声明其他生命周期接口，
    /// 否则 ABP 会按后声明的接口注册，每次解析 <c>IShell</c> 都创建新的主窗口。
    /// 非 Shell 视图按 <see cref="MvvmData.Lifetime"/> 选择接口，未指定时沿用瞬态。
    /// </remarks>
    private static string GetLifetimeInterface((ClassData Class, MvvmData Data, string Version) context)
    {
        if (context.Data.IsShell)
        {
            return string.Empty;
        }

        return context.Data.Lifetime switch
        {
            ServiceLifetimeKind.Scoped => ", global::Volo.Abp.DependencyInjection.IScopedDependency",
            ServiceLifetimeKind.Singleton => ", global::Volo.Abp.DependencyInjection.ISingletonDependency",
            _ => ", global::Volo.Abp.DependencyInjection.ITransientDependency",
        };
    }

    private static string GetExposeKeyedServices((ClassData Class, MvvmData Data, string Version) context)
    {
        if (string.IsNullOrWhiteSpace(context.Data.ViewName))
        {
            return string.Empty;
        }

        var viewName = context.Data.ViewName!.ToCSharpStringLiteral();

        return GeneratedCode.Lines(
            $"[global::Volo.Abp.DependencyInjection.ExposeKeyedService<global::Len.Abp.Wpf.Mvvm.IView>(\"{viewName}\")]",
            $"[global::Volo.Abp.DependencyInjection.ExposeKeyedService<global::Len.Abp.Wpf.Mvvm.IView<{context.Data.ViewModel}>>(\"{viewName}\")]",
            $"[global::Volo.Abp.DependencyInjection.ExposeKeyedService<{context.Class.Name}>(\"{viewName}\")]"
        );
    }

    /// <inheritdoc/>
    protected override (ClassData Class, MvvmData Data, string Version)? PrepareData((ClassContext, string) context)
    {
        var ((_, attributes, _, classSymbol), version) = context;
        if (attributes.FirstOrDefault() is not { } attribute)
        {
            return null;
        }

        var classData = classSymbol.GetClassData();
        var data = (MvvmData)attribute;

        // 用户可能已经手写了接收视图模型的构造函数，此时不再生成，避免重复定义。
        data = data with { HasViewModelConstructor = HasViewModelConstructor(classSymbol, data.ViewModel) };

        return (classData, data, version);
    }

    /// <summary>
    /// 判断类型是否已声明接收视图模型的构造函数。
    /// </summary>
    /// <param name="classSymbol">视图类型符号。</param>
    /// <param name="viewModel">视图模型的完全限定类型名。</param>
    /// <returns>存在匹配的构造函数返回 true。</returns>
    private static bool HasViewModelConstructor(INamedTypeSymbol classSymbol, string viewModel) =>
        classSymbol.InstanceConstructors.Any(constructor =>
            !constructor.IsImplicitlyDeclared
            && constructor.Parameters.Length == 1
            && string.Equals(
                constructor.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                viewModel,
                StringComparison.Ordinal
            )
        );

    /// <summary>
    /// 视图生成器所需的 MVVM 数据。
    /// </summary>
    /// <param name="IsShell">是否为 Shell 视图。</param>
    /// <param name="ViewModel">视图模型的完全限定类型名。</param>
    /// <param name="ViewName">视图名称。</param>
    /// <param name="Lifetime">视图的注册生命周期。</param>
    /// <param name="HasViewModelConstructor">视图是否已手写接收视图模型的构造函数。</param>
    public readonly record struct MvvmData(
        bool IsShell,
        string ViewModel,
        string? ViewName,
        ServiceLifetimeKind Lifetime = ServiceLifetimeKind.Transient,
        bool HasViewModelConstructor = false)
    {
        /// <summary>
        /// 从视图特性数据构造 MVVM 数据。
        /// </summary>
        /// <param name="attribute">视图特性数据。</param>
        public static implicit operator MvvmData(AttributeData attribute)
        {
            attribute = attribute ?? throw new ArgumentNullException(nameof(attribute));

            var temp = attribute.GetNamedArgument("IsShell");
            var isShell = false;
            if (!temp.IsNull)
            {
                isShell = attribute.GetNamedArgument("IsShell").To<bool>();
            }

            var typeSymbol =
                attribute.GetGenericTypeArgument(0) ?? attribute.ConstructorArguments.ElementAtOrDefault(0).Value as ITypeSymbol;
            var viewModel = typeSymbol?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) ?? string.Empty;
            var viewName = attribute.GetNamedArgument("ViewName").Value?.ToString() ?? string.Empty;

            return new MvvmData(isShell, viewModel, viewName, GetLifetime(attribute));
        }

        /// <summary>
        /// 读取生命周期命名参数。
        /// </summary>
        /// <remarks>
        /// 枚举常量在特性数据里以底层整数值存放。这里镜像
        /// <c>Microsoft.Extensions.DependencyInjection.ServiceLifetime</c> 的取值：
        /// <c>Singleton = 0</c>、<c>Scoped = 1</c>、<c>Transient = 2</c>。
        /// 未设置或取值越界时回退到瞬态。
        /// </remarks>
        private static ServiceLifetimeKind GetLifetime(AttributeData attribute)
        {
            var constant = attribute.GetNamedArgument("Lifetime");
            if (constant.IsNull)
            {
                return ServiceLifetimeKind.Transient;
            }

            return constant.To<int>() switch
            {
                0 => ServiceLifetimeKind.Singleton,
                1 => ServiceLifetimeKind.Scoped,
                _ => ServiceLifetimeKind.Transient,
            };
        }
    }

    /// <summary>
    /// 视图生命周期的生成器内部表示。
    /// </summary>
    /// <remarks>
    /// 源生成器不能引用目标程序集，因此这里镜像
    /// <c>Microsoft.Extensions.DependencyInjection.ServiceLifetime</c> 的取值，两处定义必须保持一致。
    /// </remarks>
    public enum ServiceLifetimeKind
    {
        /// <summary>
        /// 整个应用共享同一实例。
        /// </summary>
        Singleton = 0,

        /// <summary>
        /// 每个作用域内共享同一实例。
        /// </summary>
        Scoped = 1,

        /// <summary>
        /// 每次解析都创建新实例。
        /// </summary>
        Transient = 2,
    }
}
