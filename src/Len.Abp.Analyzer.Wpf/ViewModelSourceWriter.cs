using Microsoft.CodeAnalysis;

namespace Len.Abp.Analyzer;

/// <summary>
/// 生成视图模型的分部声明：导航契约成员与自动注册接口。
/// </summary>
/// <remarks>
/// <para>
/// 视图模型的分部声明单独成文件，与视图分开。必须聚合后按视图模型去重：
/// 一个视图模型可能被多个视图共用，逐个产出会得到同名 hint name（CS8785）。
/// </para>
/// <para>
/// 契约成员与自动注册的条件不同：契约只要求视图模型是 <c>partial</c>，
/// 自动注册还要求构造函数可注入。因此两者分别判断，任一成立都要生成声明。
/// </para>
/// </remarks>
internal static class ViewModelSourceWriter
{
    /// <summary>
    /// 生成视图模型源文件的完整内容。
    /// </summary>
    /// <param name="context">类数据、生成器数据与版本号。</param>
    /// <returns>视图模型源文件；不需要生成时返回空字符串。</returns>
    public static string CreateSourceCode((ClassData Class, MvvmData Data, string Version) context) =>
        GeneratedCode.Join(
            "// <auto-generated />",
            "#nullable enable",
            GetViewModelRegistration(context)
        );

    /// <summary>
    /// 生成视图模型源文件的名称。
    /// </summary>
    /// <param name="viewModel">视图模型的类型信息。</param>
    /// <returns>源文件名。</returns>
    /// <remarks>
    /// <para>
    /// 按**视图模型**而不是视图命名：一个视图模型可能被多个视图共用
    /// （示例里 <c>RegionTabPageViewModel</c> 被三个选项卡页面共用），
    /// 按视图命名会产出同名 hint name，Roslyn 抛异常导致零产出（CS8785）。
    /// </para>
    /// <para>
    /// 用 <see cref="ClassData.HintName"/> 而不是闭合类型名：后者对
    /// <c>PageViewModel&lt;int&gt;</c> 与 <c>PageViewModel&lt;string&gt;</c> 给出不同文本，
    /// 但两者是同一个分部声明，各产出一份会撞 CS0102 重复成员。
    /// 按声明目标去重后只会有一份文件，因此文件名也必须按声明目标生成。
    /// </para>
    /// </remarks>
    public static string CreateFileName(ClassData viewModel) =>
        $"{viewModel.HintName}.{nameof(MvvmGenerator)}.ViewModel.g.cs";

    /// <summary>
    /// 从所有视图的生成数据中提取视图模型源文件，按分部声明目标去重。
    /// </summary>
    /// <param name="items">所有视图的类数据、生成器数据与版本号。</param>
    /// <returns>视图模型源文件集合。</returns>
    /// <remarks>
    /// <para>
    /// <b>去重键是分部声明目标，不是闭合类型。</b>多个视图共用同一个视图模型时，
    /// 契约成员与生命周期接口只应生成一次，否则会产生重复成员（CS0102）与同名 hint name（CS8785）。
    /// </para>
    /// <para>
    /// <c>PageViewModel&lt;int&gt;</c> 与 <c>PageViewModel&lt;string&gt;</c> 是同一个分部声明
    /// <c>partial class PageViewModel&lt;T&gt;</c> 的两个闭合实例，按闭合类型去重会让两者各产出一份，
    /// 撞 CS0102。因此必须按 <see cref="ClassData.DeclarationKey"/> 分组。
    /// </para>
    /// <para>
    /// 同一分组内必须**合并**必需参数：不同视图对同一个视图模型可以声明不同的
    /// <c>RequiredParameters</c>，只保留第一份会让其余视图的契约静默失效。
    /// </para>
    /// </remarks>
    public static IEnumerable<FileWithName> CreateFiles(
        IReadOnlyList<(ClassData Class, MvvmData Data, string Version)> items)
    {
        var groups = new Dictionary<string, ViewModelGroup>(StringComparer.Ordinal);
        var order = new List<string>();

        foreach (var item in items)
        {
            var target = item.Data.ViewModelContract?.Class ?? item.Data.ViewModelRegistration?.Class;

            if (target is not { } viewModel)
            {
                continue;
            }

            if (!groups.TryGetValue(viewModel.DeclarationKey, out var group))
            {
                group = new ViewModelGroup(viewModel, item.Version);
                groups.Add(viewModel.DeclarationKey, group);
                order.Add(viewModel.DeclarationKey);
            }

            group.Add(item.Data);
        }

        foreach (var key in order)
        {
            var group = groups[key];
            var text = CreateSourceCode((group.Target, group.Merge(), group.Version));

            if (string.IsNullOrEmpty(text))
            {
                continue;
            }

            yield return new FileWithName(CreateFileName(group.Target), text);
        }
    }

    /// <summary>
    /// 同一个分部声明目标下累积的视图数据。
    /// </summary>
    /// <remarks>
    /// 分组期间只累积，不生成：必需参数必须看到全部视图才能合并，
    /// 逐个生成会让先处理的视图决定最终契约。
    /// </remarks>
    private sealed class ViewModelGroup(ClassData target, string version)
    {
        private readonly List<MvvmData> _datas = [];

        /// <summary>
        /// 获取分部声明的目标类型。
        /// </summary>
        public ClassData Target { get; } = target;

        /// <summary>
        /// 获取生成器版本号。
        /// </summary>
        public string Version { get; } = version;

        /// <summary>
        /// 累积一个视图的生成数据。
        /// </summary>
        /// <param name="data">视图的生成数据。</param>
        public void Add(MvvmData data) => _datas.Add(data);

        /// <summary>
        /// 把分组内所有视图的数据合并成一份。
        /// </summary>
        /// <returns>用于生成分部声明的数据。</returns>
        /// <remarks>
        /// <para>
        /// 注册信息与契约位置取第一个非空值：同一视图模型的所有视图读到的位置完全相同，
        /// 差异只可能来自生命周期声明，那种情况以处理顺序为准。
        /// </para>
        /// <para>
        /// 必需参数取并集，按名称（不区分大小写）去重，与导航参数校验器的匹配口径一致。
        /// </para>
        /// </remarks>
        public MvvmData Merge()
        {
            var parameters = new List<RequiredParameter>();
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            foreach (var data in _datas)
            {
                foreach (var parameter in data.RequiredParameters)
                {
                    if (seen.Add(parameter.Name))
                    {
                        parameters.Add(parameter);
                    }
                }
            }

            return _datas[0] with
            {
                RequiredParameters = parameters,
                ViewModelRegistration = _datas.Select(data => data.ViewModelRegistration).FirstOrDefault(value => value is not null),
                ViewModelContract = _datas.Select(data => data.ViewModelContract).FirstOrDefault(value => value is not null),
            };
        }
    }

    /// <summary>
    /// 生成视图模型的分部声明：契约成员，以及（可选）自动注册接口。
    /// </summary>
    /// <param name="context">类数据、生成器数据与版本号。</param>
    /// <returns>视图模型的分部声明；不需要生成时返回空字符串。</returns>
    /// <remarks>
    /// 位置信息取自视图模型自己的 <see cref="ClassData"/>：外层类型链与类型种类
    /// （<c>record</c>）都必须保留，否则嵌套视图模型会被声明到幽灵类型上，
    /// record 视图模型会被生成成 <c>partial class</c>（CS0261）。
    /// </remarks>
    private static string GetViewModelRegistration((ClassData Class, MvvmData Data, string Version) context)
    {
        var contract = context.Data.ViewModelContract;
        var registration = context.Data.ViewModelRegistration;

        if (contract is null && registration is null)
        {
            return string.Empty;
        }

        // 契约与注册可能指向同一个视图模型；以契约的位置为准，注册只补接口。
        var target = contract?.Class ?? registration!.Value.Class;

        var baseTypes = new List<string>();

        if (registration is { } value)
        {
            baseTypes.Add(value.Lifetime.ToDependencyInterface());
        }

        if (context.Data.RequiredParameters.Count > 0)
        {
            baseTypes.Add("global::Len.Abp.Wpf.Navigation.INavigationContract");
        }

        var declaration = target.WrapInTypeDeclarations(GetRequiredNavigationParameters(context), target.SelfDeclaration(baseTypes));

        // 一律用块作用域包裹：裸声明会落到全局命名空间，
        // 与视图模型真正的类型是两个类型，接口实现静默丢失。
        // 视图与视图模型分属两个文件，因此不会与视图侧的文件作用域命名空间冲突（CS8955）。
        return WrapInBlockNamespace(target.Namespace, declaration);
    }

    /// <summary>
    /// 把代码包进块作用域命名空间。
    /// </summary>
    /// <param name="namespace">命名空间；为空表示全局命名空间。</param>
    /// <param name="body">左对齐的代码。</param>
    /// <returns>带块作用域命名空间的代码。</returns>
    private static string WrapInBlockNamespace(string @namespace, string body)
    {
        if (string.IsNullOrEmpty(@namespace))
        {
            return body;
        }

        return GeneratedCode.Lines(
            $"namespace {@namespace}",
            "{",
            GeneratedCode.Inline("    ", body, 4),
            "}"
        );
    }

    /// <summary>
    /// 生成导航必需参数：静态只读字典字段，加上转发它的实例属性。
    /// </summary>
    /// <param name="context">类数据、生成器数据与版本号。</param>
    /// <returns>契约成员代码；未声明必需参数时返回空字符串。</returns>
    /// <remarks>
    /// <para>
    /// 键为参数名，值为参数类型；类型为 <see langword="null"/> 表示只校验存在性。
    /// 使用 <see cref="StringComparer.OrdinalIgnoreCase"/> 与校验器的大小写不敏感匹配一致：
    /// <c>IParameters</c> 本身的键比较是大小写敏感的，但导航参数校验刻意放宽，
    /// 避免参数来自查询串时因大小写差异被判为缺失。
    /// 未声明必需参数时不生成成员，沿用 <c>INavigationContract</c> 的默认实现。
    /// </para>
    /// <para>
    /// 成员生成到**视图模型**而不是视图：视图模型才是参数的消费者，
    /// 框架的其它导航契约（<c>INavigationAware</c>）也都在视图模型上。
    /// 视图模型是普通类，测试里直接 <c>new</c> 就能断言契约；
    /// 视图是 WPF 控件，测试通常只能用替身，真实产出从未被验证过。
    /// </para>
    /// <para>
    /// 必须是实例属性：<c>INavigationContract.RequiredNavigationParameters</c> 是实例成员，
    /// 只生成静态属性时类不会实现该接口成员，编译器静默回落到接口默认实现，
    /// 校验器读到的永远是空字典。
    /// </para>
    /// <para>
    /// 数据本身放在静态字段里：字典内容在编译期确定，所有实例共享一份即可，
    /// 不必每个视图模型实例各建一份。实例属性只做转发，不产生额外分配。
    /// </para>
    /// </remarks>
    private static string GetRequiredNavigationParameters((ClassData Class, MvvmData Data, string Version) context)
    {
        if (context.Data.RequiredParameters.Count == 0)
        {
            return string.Empty;
        }

        var entries = context.Data.RequiredParameters
            .Select(parameter =>
                $"        [\"{parameter.Name.ToCSharpStringLiteral()}\"] = {(parameter.Type is null ? "null" : $"typeof({parameter.Type})")},"
            )
            .ToArray();

        return GeneratedCode.Lines(
            "/// <summary>",
            "/// 获取导航到本视图时必须提供的参数：键为参数名，值为参数类型；",
            "/// 值为 <see langword=\"null\"/> 表示只校验存在性。",
            "/// </summary>",
            GeneratedCode.GeneratedMemberAttributes(nameof(MvvmGenerator), context.Version),
            "public global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Type?> RequiredNavigationParameters => RequiredNavigationParametersValue;",
            string.Empty,
            GeneratedCode.GeneratedMemberAttributes(nameof(MvvmGenerator), context.Version),
            "private static readonly global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Type?> RequiredNavigationParametersValue =",
            "    new global::System.Collections.Generic.Dictionary<string, global::System.Type?>(global::System.StringComparer.OrdinalIgnoreCase)",
            "    {",
            string.Join("\n", entries),
            "    };"
        );
    }
}
