using Microsoft.CodeAnalysis;

namespace Len.Abp.Analyzer;

/// <summary>
/// 生成视图类型本身的分部声明：<c>IView</c> 实现、注册特性与构造函数。
/// </summary>
/// <remarks>
/// 只负责文本拼装，不判断"要不要生成"——前置条件由
/// <see cref="MvvmGenerator.PrepareData"/> 决定，诊断由 <see cref="MvvmDiagnostics"/> 报告。
/// 视图与视图模型各自成文件，模板分别集中在本类与 <see cref="ViewModelSourceWriter"/>，
/// 生成器本体只保留管线编排。
/// </remarks>
internal static class ViewSourceWriter
{
    /// <summary>
    /// 生成视图源文件的完整内容。
    /// </summary>
    /// <param name="context">类数据、生成器数据与版本号。</param>
    /// <returns>视图源文件。</returns>
    public static string CreateSourceCode((ClassData Class, MvvmData Data, string Version) context)
    {
        var baseTypes = new List<string>();

        if (context.Data.IsShell)
        {
            baseTypes.Add("global::Len.Abp.Wpf.IShell");
        }

        baseTypes.Add($"global::Len.Abp.Wpf.Mvvm.IView<{context.Data.ViewModel}>");
        baseTypes.AddRange(GetLifetimeInterface(context));

        var selfDeclaration = context.Class.SelfDeclaration(baseTypes);

        var members = GeneratedCode.Join(
            GeneratedCode.Lines(
                "///<inheritdoc/>",
                GeneratedCode.GeneratedMemberAttributes(nameof(MvvmGenerator), context.Version),
                $"public {context.Data.ViewModel} ViewModel => ({context.Data.ViewModel})DataContext;"
            ),
            GeneratedCode.Lines(
                "///<inheritdoc/>",
                GeneratedCode.GeneratedMemberAttributes(nameof(MvvmGenerator), context.Version),
                "object global::Len.Abp.Wpf.Mvvm.IView.ViewModel => ViewModel;"
            ),
            GeneratedCode.Lines(
                "///<inheritdoc/>",
                GeneratedCode.GeneratedMemberAttributes(nameof(MvvmGenerator), context.Version),
                $"public string ViewName => \"{(context.Data.ViewName ?? string.Empty).ToCSharpStringLiteral()}\";"
            ),
            GetConstructor(context)
        );

        // 特性必须紧贴最内层类型声明：拼在整个块之前时，编译器会把它绑定到外层类型，
        // 嵌套视图的注册特性会因此挂错目标。
        // 这里用 Type（已闭合的完全限定名）而不是 DeclarationName：typeof() 需要具体类型，
        // 未闭合的类型参数在特性参数里是 CS0416。
        // 不再额外注册 IView<object>：IView<out T> 本就协变，IView<DemoViewModel>
        // 可以直接当作 IView<object> 使用，多注册一个服务接口没有解析点。
        var attributes = GetExposeKeyedServices(context)
            + $"[global::Volo.Abp.DependencyInjection.ExposeServices({(context.Data.IsShell ? "typeof(global::Len.Abp.Wpf.IShell), " : string.Empty)}typeof({context.Class.Type}), typeof(global::Len.Abp.Wpf.Mvvm.IView<{context.Data.ViewModel}>))]\n";

        var viewDeclaration = context.Class.WrapInTypeDeclarations(members, selfDeclaration, attributes);

        // 文件里只有视图一个类型，命名空间固定用文件作用域即可。
        return GeneratedCode.Join(
            "// <auto-generated />",
            "#nullable enable",
            context.Class.NamespaceDeclaration,
            viewDeclaration
        );
    }

    /// <summary>
    /// 生成视图的生命周期标记接口。
    /// </summary>
    /// <param name="context">类数据、生成器数据与版本号。</param>
    /// <returns>生命周期接口；Shell 视图不声明任何生命周期接口，返回空集合。</returns>
    /// <remarks>
    /// <c>IShell</c> 本身继承 <c>ISingletonDependency</c>，Shell 视图不能再声明其他生命周期接口，
    /// 否则 ABP 会按后声明的接口注册，每次解析 <c>IShell</c> 都创建新的主窗口。
    /// 非 Shell 视图按 <see cref="MvvmData.Lifetime"/> 选择接口，未指定时沿用瞬态。
    /// </remarks>
    private static IReadOnlyList<string> GetLifetimeInterface((ClassData Class, MvvmData Data, string Version) context) =>
        context.Data.IsShell ? [] : [context.Data.Lifetime.ToDependencyInterface()];

    /// <summary>
    /// 生成按视图名注册的键控服务特性。
    /// </summary>
    /// <param name="context">类数据、生成器数据与版本号。</param>
    /// <returns>三行键控注册特性；视图不参与导航时返回空字符串。</returns>
    private static string GetExposeKeyedServices((ClassData Class, MvvmData Data, string Version) context)
    {
        if (string.IsNullOrWhiteSpace(context.Data.ViewName))
        {
            return string.Empty;
        }

        var viewName = context.Data.ViewName!.ToCSharpStringLiteral();

        return GeneratedCode.Lines(
            $"[global::Volo.Abp.DependencyInjection.ExposeKeyedService<global::Len.Abp.Wpf.Mvvm.IView>(\"{viewName}\")]",
            $"[global::Volo.Abp.DependencyInjection.ExposeKeyedService<global::Len.Abp.Wpf.Mvvm.IView<{context.Data.ViewModel}>>(\"{viewName}\")]",
            $"[global::Volo.Abp.DependencyInjection.ExposeKeyedService<{context.Class.Type}>(\"{viewName}\")]"
        );
    }

    /// <summary>
    /// 生成通过构造函数注入视图模型的构造函数。
    /// </summary>
    /// <param name="context">类数据、生成器数据与版本号。</param>
    /// <returns>构造函数代码；用户已手写接收视图模型的构造函数时返回空字符串。</returns>
    /// <remarks>
    /// <para>
    /// 视图由容器解析，构造函数注入让依赖显式可见，且不依赖 Autofac 的属性注入。
    /// <c>: this()</c> 链到无参构造函数，保证 <c>InitializeComponent</c> 照常执行。
    /// 用户已手写接收视图模型的构造函数时不再生成，避免重复成员。
    /// </para>
    /// <para>
    /// 视图完全没有显式构造函数时必须自己补一个无参构造函数：分部类一旦有构造函数，
    /// 编译器就不再合成无参构造，<c>: this()</c> 会找不到目标（CS7036）。
    /// 补的那个在视图有 <c>InitializeComponent</c>（即带 XAML）时调用它，
    /// 否则生成的视图会缺少视觉树。
    /// </para>
    /// </remarks>
    private static string GetConstructor((ClassData Class, MvvmData Data, string Version) context)
    {
        if (context.Data.HasViewModelConstructor)
        {
            return string.Empty;
        }

        var injected = GeneratedCode.Lines(
            "/// <summary>",
            "/// 注入视图模型并写入 <c>DataContext</c>。",
            "/// </summary>",
            GeneratedCode.GeneratedMemberAttributes(nameof(MvvmGenerator), context.Version),
            $"public {context.Class.SimpleName}({context.Data.ViewModel} viewModel) : this()",
            "{",
            "    DataContext = viewModel;",
            "}"
        );

        // 用户已声明无参构造函数时直接链过去，不重复生成。
        if (context.Class.HasAnyConstructor)
        {
            return injected;
        }

        var parameterless = GeneratedCode.Lines(
            "/// <summary>",
            "/// 初始化视图。",
            "/// </summary>",
            GeneratedCode.GeneratedMemberAttributes(nameof(MvvmGenerator), context.Version),
            $"public {context.Class.SimpleName}()",
            "{",
            context.Class.HasMethod("InitializeComponent") ? "    InitializeComponent();" : null,
            "}"
        );

        return GeneratedCode.Join(parameterless, injected);
    }
}
