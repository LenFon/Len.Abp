using Len.Abp.Analyzer;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

/// <summary>
/// 从特性生成 WPF 路由事件的生成器共享流程。
/// 派生生成器只提供生成的成员，这部分在实例事件和附加事件之间不同。
/// </summary>
internal abstract class RoutedEventGeneratorBase(string id, params HashSet<string> attributeFullyNames)
    : BasicGenerator<RoutedEventGeneratorBase.RoutedEventData>(id, attributeFullyNames)
{
    /// <summary>
    /// 生成成员上 <c>GeneratedCode</c> 特性所标注的生成器名称。
    /// </summary>
    protected abstract string GeneratorName { get; }

    /// <summary>
    /// 路由事件字段的 XML 文档中使用的类型描述，例如“路由事件”或“附加路由事件”。
    /// </summary>
    protected abstract string EventKindDescription { get; }

    /// <inheritdoc/>
    protected override string CreateFileName((ClassData Class, RoutedEventData Data, string Version) context) =>
        $"{context.Class.HintName}.{context.Data.Name}.g.cs";

    /// <inheritdoc/>
    protected override string CreateSourceCode((ClassData Class, RoutedEventData Data, string Version) context)
    {
        var summary = EventKindDescription.Length == 0
            ? $"/// 标识 <see cref=\"{context.Data.Name}\"/>。"
            : $"/// 标识 {context.Data.Name} {EventKindDescription}。";

        var members = GeneratedCode.Join(
            GeneratedCode.Lines(
                "/// <summary>",
                summary,
                "/// </summary>",
                "[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]",
                $"[global::System.CodeDom.Compiler.GeneratedCode(\"{GeneratorName}\", \"{context.Version}\")]",
                $"public static readonly global::System.Windows.RoutedEvent {context.Data.Name}Event = global::System.Windows.EventManager.RegisterRoutedEvent(",
                $"    \"{context.Data.Name}\",",
                $"    {context.Data.Strategy},",
                $"    typeof({context.Data.Type}),",
                $"    typeof({context.Class.Type})",
                ");"
            ),
            GenerateMembers(context)
        );

        return GeneratedCode.Join(
            "// <auto-generated />",
            "#nullable enable",
            context.Class.NamespaceDeclaration,
            context.Class.WrapInTypeDeclarations(members)
        );
    }

    /// <summary>
    /// 生成路由事件的事件访问器以及触发辅助方法。
    /// </summary>
    protected abstract string GenerateMembers((ClassData Class, RoutedEventData Data, string Version) context);

    /// <inheritdoc/>
    protected override (ClassData Class, RoutedEventData Data, string Version)? PrepareData((ClassContext, string) context)
    {
        var ((_, attributes, _, classSymbol), version) = context;
        if (attributes.FirstOrDefault() is not { } attribute)
        {
            return null;
        }

        var classData = classSymbol.GetClassData();

        return (classData, attribute, version);
    }

    /// <summary>
    /// 生成路由事件所需的全部数据。
    /// </summary>
    /// <param name="Name">事件名称。</param>
    /// <param name="Type">事件处理程序委托的完全限定类型名。</param>
    /// <param name="EventArgs">事件参数类型的完全限定名。</param>
    /// <param name="Strategy">路由策略。</param>
    /// <param name="Description">事件的描述。</param>
    /// <param name="Category">事件的分类。</param>
    public readonly record struct RoutedEventData(
        string Name,
        string Type,
        string EventArgs,
        string Strategy,
        string? Description,
        string? Category
    )
    {
        /// <summary>
        /// 从特性数据构造路由事件数据。
        /// </summary>
        /// <param name="attribute">路由事件特性数据。</param>
        public static implicit operator RoutedEventData(AttributeData attribute)
        {
            attribute = attribute ?? throw new ArgumentNullException(nameof(attribute));

            var name = attribute.ConstructorArguments.ElementAtOrDefault(0).Value?.ToString() ?? string.Empty;
            var strategy = $"global::{attribute.ConstructorArguments.ElementAt(1).ToCSharpString()}";
            var typeSymbol =
                attribute.GetGenericTypeArgument(0) ?? attribute.ConstructorArguments.ElementAtOrDefault(2).Value as ITypeSymbol;

            string type;
            string eventArgs;
            if (typeSymbol is null)
            {
                type = "global::System.Windows.RoutedEventHandler";
                eventArgs = "global::System.Windows.RoutedEventArgs";
            }
            else
            {
                type = typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                eventArgs = ((INamedTypeSymbol)typeSymbol)
                    .DelegateInvokeMethod!.Parameters[1]
                    .Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            }

            var description = attribute.GetNamedArgument("Description").Value?.ToString();
            var category = attribute.GetNamedArgument("Category").Value?.ToString();

            return new RoutedEventData(name, type, eventArgs, strategy, description, category);
        }
    }
}
